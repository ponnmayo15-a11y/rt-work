"""単位種別・所要区分から取得単位(ポイント)数を算出する

日本X線CT専門技師認定機構「X線CT認定技師の更新条件について(平成25年4月改訂)」の
基準表に基づく。「本機構が認定した講習会等」(=単位認定講習会等一覧に掲載される回)は
種別Ⅱ-3、関連団体(JSRT/JART/JRS)主催の学会・講習会は種別Ⅱ-2に相当する。
"""

POINTS_TABLE = {
    ("Ⅱ-1", "半日未満"): 3,
    ("Ⅱ-1", "半日"): 7,
    ("Ⅱ-1", "一日以上"): 14,
    ("Ⅱ-2", "半日未満"): 2,
    ("Ⅱ-2", "半日"): 5,
    ("Ⅱ-2", "一日以上"): 10,
    ("Ⅱ-3", "半日未満"): 1,
    ("Ⅱ-3", "半日"): 3,
    ("Ⅱ-3", "一日以上"): 6,
}


def lookup(category: str, duration: str) -> int | None:
    return POINTS_TABLE.get((category.strip(), duration.strip()))
